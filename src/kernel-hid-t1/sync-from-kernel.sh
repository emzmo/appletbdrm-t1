#!/bin/bash
# sync-from-kernel.sh — Developer tool to regenerate vendored hid-multitouch
# source files from a full kernel source tree.
#
# Usage:
#   ./sync-from-kernel.sh /path/to/kernel/source
#   ./sync-from-kernel.sh            # auto-detect (uses /usr/src/linux, etc.)
#   ./sync-from-kernel.sh --tarball linux-6.18.42.tar.xz
#
# This tool:
#   1. Copies hid-multitouch.c, hid-ids.h, hid-haptic.h from the kernel source
#   2. Applies the T1 patches (t1-ids.patch, t1-touch.patch)
#   3. Verifies the patched source compiles (optional, if KDIR available)
#   4. Updates a version stamp file
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
VENDORED_DIR="$SCRIPT_DIR/src"
PATCH_DIR="$SCRIPT_DIR/patches"
STAMP_FILE="$VENDORED_DIR/.vendored_from"

die() { echo "ERROR: $*" >&2; exit 1; }

find_kernel_src() {
    for p in /usr/src/linux /usr/src/linux-lts "/usr/src/linux-$1" /lib/modules/"$1"/source; do
        [ -f "$p/drivers/hid/hid-multitouch.c" ] && echo "$p" && return 0
    done
    return 1
}

# --- Parse args ---
KSRC=""

if [ "${1:-}" = "--tarball" ]; then
    TARBALL="${2:-}"
    [ -z "$TARBALL" ] && die "Usage: $0 --tarball <linux-X.Y.Z.tar.xz>"
    [ -f "$TARBALL" ] || die "Tarball not found: $TARBALL"
    TMP=$(mktemp -d)
    trap 'rm -rf "$TMP"' EXIT
    echo "Extracting $TARBALL..."
    tar xf "$TARBALL" -C "$TMP"
    KSRC="$TMP/$(ls "$TMP" | head -1)"
    echo "Kernel source at: $KSRC"
elif [ -n "${1:-}" ]; then
    KSRC="$1"
else
    KVER="$(uname -r)"
    KSRC="$(find_kernel_src "$KVER" || true)"
    [ -z "$KSRC" ] && die "No kernel source found. Pass path as arg or use --tarball."
fi

[ -f "$KSRC/drivers/hid/hid-multitouch.c" ] || die "Not a kernel source: $KSRC (no drivers/hid/hid-multitouch.c)"

# --- Get kernel version ---
KVER=$(make -s -C "$KSRC" kernelversion 2>/dev/null || echo "unknown")
echo "Kernel version: $KVER"

# --- 1. Copy source files ---
echo "Copying source files..."
cp "$KSRC/drivers/hid/hid-multitouch.c" "$VENDORED_DIR/"
cp "$KSRC/drivers/hid/hid-ids.h" "$VENDORED_DIR/"

# hid-haptic.h may not exist on older kernels
if [ -f "$KSRC/drivers/hid/hid-haptic.h" ]; then
    cp "$KSRC/drivers/hid/hid-haptic.h" "$VENDORED_DIR/"
else
    echo "WARN: hid-haptic.h not found in kernel source — keeping existing copy"
fi

# --- 2. Apply T1 patches ---
echo "Applying T1 patches..."

# Check if already patched
if grep -q "USB_DEVICE_ID_APPLE_IBRIDGE" "$VENDORED_DIR/hid-multitouch.c"; then
    echo "  hid-multitouch.c already has IBRIDGE — skipping touch patch"
else
    if patch -p1 -d "$VENDORED_DIR/.." < "$PATCH_DIR/t1-touch.patch" 2>/dev/null; then
        echo "  Applied t1-touch.patch"
    else
        echo "  WARN: t1-touch.patch failed — manual review needed"
        # Try a more targeted approach
        if grep -q "USB_DEVICE_ID_APPLE_TOUCHBAR_DISPLAY" "$VENDORED_DIR/hid-multitouch.c"; then
            echo "  Attempting targeted insertion..."
            # Find the line with TOUCHBAR_DISPLAY and insert after its closing
            sed -i '/USB_DEVICE_ID_APPLE_TOUCHBAR_DISPLAY)/a\\t/* Apple iBridge (T1) Touch Bar in USB Configuration 2 */\n\t{ .driver_data = MT_CLS_APPLE_TOUCHBAR,\n\t\tHID_USB_DEVICE(USB_VENDOR_ID_APPLE,\n\t\t\tUSB_DEVICE_ID_APPLE_IBRIDGE) },' "$VENDORED_DIR/hid-multitouch.c" || true
        fi
    fi
fi

if grep -q "USB_DEVICE_ID_APPLE_IBRIDGE" "$VENDORED_DIR/hid-ids.h"; then
    echo "  hid-ids.h already has IBRIDGE — skipping ids patch"
else
    if patch -p1 -d "$VENDORED_DIR/.." < "$PATCH_DIR/t1-ids.patch" 2>/dev/null; then
        echo "  Applied t1-ids.patch"
    else
        echo "  WARN: t1-ids.patch failed — adding manually"
        # Insert after TOUCHBAR_DISPLAY define
        sed -i '/^#define USB_DEVICE_ID_APPLE_TOUCHBAR_DISPLAY/a\#ifndef USB_DEVICE_ID_APPLE_IBRIDGE\n#define USB_DEVICE_ID_APPLE_IBRIDGE\t\t0x8600\n#endif' "$VENDORED_DIR/hid-ids.h" || true
    fi
fi

# --- 3. Verify ---
echo ""
echo "=== Verification ==="
if grep -q "USB_DEVICE_ID_APPLE_IBRIDGE" "$VENDORED_DIR/hid-ids.h"; then
    echo "  hid-ids.h: USB_DEVICE_ID_APPLE_IBRIDGE present ✓"
else
    echo "  hid-ids.h: MISSING IBRIDGE define ✗"
fi
if grep -q "USB_DEVICE_ID_APPLE_IBRIDGE" "$VENDORED_DIR/hid-multitouch.c"; then
    echo "  hid-multitouch.c: IBRIDGE entry in mt_devices ✓"
else
    echo "  hid-multitouch.c: MISSING IBRIDGE entry ✗"
fi

# --- 4. Write stamp ---
cat > "$STAMP_FILE" << EOF
# This file tracks the kernel version the vendored files were synced from.
# Generated by sync-from-kernel.sh — do not edit manually.
kernel_version=$KVER
synced_at=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
EOF

echo ""
echo "Done. Vendored source updated from kernel $KVER."
echo "Files in: $VENDORED_DIR"